"""Declarative base and column helpers shared by every model.

The models mirror docs/database/INITIAL_SCHEMA_SQL.md. Database defaults are
declared with ``server_default`` so the schema created by Alembic matches the
documented SQL, and ``alembic check`` stays clean.
"""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    DateTime,
    ForeignKeyConstraint,
    MetaData,
    Uuid,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.ext.asyncio import AsyncAttrs
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column
from sqlalchemy.types import UserDefinedType

# Names for constraints the schema leaves unnamed. These match PostgreSQL's own
# defaults (<table>_<cols>_fkey, <table>_pkey), so the database and the models
# agree. Explicitly named constraints keep the names from the schema docs.
NAMING_CONVENTION = {
    "ix": "%(table_name)s_%(column_0_N_name)s_idx",
    "uq": "%(table_name)s_%(column_0_N_name)s_key",
    "fk": "%(table_name)s_%(column_0_N_name)s_fkey",
    "pk": "%(table_name)s_pkey",
}


class Base(AsyncAttrs, DeclarativeBase):
    """Base class for all models."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    type_annotation_map = {
        dict[str, Any]: JSONB,
        list[Any]: JSONB,
    }


# ---------------------------------------------------------------------------
# Custom column types
# ---------------------------------------------------------------------------


class CIText(UserDefinedType[str]):
    """PostgreSQL ``citext`` (case-insensitive text, from the citext extension)."""

    cache_ok = True

    def get_col_spec(self, **kw: Any) -> str:
        return "CITEXT"


# ---------------------------------------------------------------------------
# Column helpers
# ---------------------------------------------------------------------------


def uuid_pk() -> Mapped[uuid.UUID]:
    return mapped_column(
        Uuid, primary_key=True, server_default=text("gen_random_uuid()")
    )


def created_at_col() -> Mapped[datetime]:
    return mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("NOW()")
    )


def updated_at_col() -> Mapped[datetime]:
    # The set_updated_at() trigger maintains this in the database; onupdate
    # keeps the in-memory object current after an ORM flush.
    return mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=text("NOW()"),
        onupdate=text("NOW()"),
    )


def deleted_at_col() -> Mapped[datetime | None]:
    return mapped_column(DateTime(timezone=True), nullable=True)


def jsonb_object(name: str | None = None) -> Mapped[dict[str, Any]]:
    """NOT NULL jsonb object. Pass ``name`` when the attribute name differs from
    the column, e.g. ``metadata`` (reserved on declarative classes)."""
    if name:
        return mapped_column(
            name, JSONB, nullable=False, server_default=text("'{}'::jsonb")
        )
    return mapped_column(JSONB, nullable=False, server_default=text("'{}'::jsonb"))


def jsonb_array() -> Mapped[list[Any]]:
    return mapped_column(JSONB, nullable=False, server_default=text("'[]'::jsonb"))


def random_token_default() -> Any:
    """48-hex-char random token, generated by the database (pgcrypto)."""
    return text("encode(gen_random_bytes(24), 'hex')")


# ---------------------------------------------------------------------------
# Tenant foreign keys
# ---------------------------------------------------------------------------


def workspace_fk() -> ForeignKeyConstraint:
    """(organization_id, workspace_id) → workspaces: org and workspace can't disagree."""
    return ForeignKeyConstraint(
        ["organization_id", "workspace_id"],
        ["workspaces.organization_id", "workspaces.id"],
        ondelete="CASCADE",
    )


def ws_fk(
    column: str, target_table: str, ondelete: str = "CASCADE"
) -> ForeignKeyConstraint:
    """(workspace_id, <column>) → <target_table>(workspace_id, id).

    Guarantees the referenced row lives in the same workspace. For nullable
    references pass ``ondelete="SET NULL"``: only <column> is cleared, never
    workspace_id (PostgreSQL 15+ ``SET NULL (column)``).
    """
    if ondelete == "SET NULL":
        ondelete = f"SET NULL ({column})"
    return ForeignKeyConstraint(
        ["workspace_id", column],
        [f"{target_table}.workspace_id", f"{target_table}.id"],
        ondelete=ondelete,
    )


def org_fk(
    column: str,
    target_table: str,
    ondelete: str = "CASCADE",
    name: str | None = None,
) -> ForeignKeyConstraint:
    """(organization_id, <column>) → <target_table>(organization_id, id)."""
    if ondelete == "SET NULL":
        ondelete = f"SET NULL ({column})"
    return ForeignKeyConstraint(
        ["organization_id", column],
        [f"{target_table}.organization_id", f"{target_table}.id"],
        ondelete=ondelete,
        name=name,
    )
